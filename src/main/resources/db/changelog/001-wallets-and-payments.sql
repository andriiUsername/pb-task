CREATE TABLE wallet
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   VARCHAR(255)   NOT NULL,
    currency   VARCHAR(3)     NOT NULL,
    balance    NUMERIC(19, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT ck_wallet_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_wallet_balance_not_negative CHECK (balance >= 0)
);
--rollback DROP TABLE wallet;

--changeset privatbank-task:create-payment-table
CREATE TABLE payment
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(16)    NOT NULL,
    status           VARCHAR(16)    NOT NULL,
    source_wallet_id BIGINT REFERENCES wallet (id),
    target_wallet_id BIGINT REFERENCES wallet (id),
    amount           NUMERIC(19, 2) NOT NULL,
    currency         VARCHAR(3)     NOT NULL,
    idempotency_key  VARCHAR(100)   NOT NULL,
    created_by       VARCHAR(255)   NOT NULL,
    created_at       TIMESTAMPTZ    NOT NULL,
    confirmed_by     VARCHAR(255),
    completed_at     TIMESTAMPTZ,
    CONSTRAINT uk_payment_created_by_idempotency_key UNIQUE (created_by, idempotency_key),
    CONSTRAINT ck_payment_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_payment_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_payment_completion CHECK (
        (status = 'CREATED' AND confirmed_by IS NULL AND completed_at IS NULL)
            OR (status = 'COMPLETED' AND confirmed_by IS NOT NULL AND completed_at IS NOT NULL)
        ),
    CONSTRAINT ck_payment_wallets CHECK (
        (type = 'TOP_UP' AND source_wallet_id IS NULL AND target_wallet_id IS NOT NULL)
            OR (type = 'WITHDRAWAL' AND source_wallet_id IS NOT NULL AND target_wallet_id IS NULL)
            OR (type = 'TRANSFER' AND source_wallet_id IS NOT NULL AND target_wallet_id IS NOT NULL
                AND source_wallet_id <> target_wallet_id)
        )
);
CREATE INDEX ix_payment_source_wallet_id ON payment (source_wallet_id);
CREATE INDEX ix_payment_target_wallet_id ON payment (target_wallet_id);
--rollback DROP TABLE payment;
