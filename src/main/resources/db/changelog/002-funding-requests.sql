CREATE TABLE funding_schedule_item
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funding_request_id BIGINT         NOT NULL REFERENCES funding_request (id),
    due_date           DATE           NOT NULL,
    amount             NUMERIC(19, 2) NOT NULL,
    payment_id         BIGINT REFERENCES payment (id),
    paid_at            TIMESTAMPTZ,
    CONSTRAINT uk_funding_schedule_item_payment UNIQUE (payment_id),
    CONSTRAINT ck_funding_schedule_item_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_funding_schedule_item_paid_has_payment CHECK (paid_at IS NULL OR payment_id IS NOT NULL)
);
CREATE INDEX ix_funding_schedule_item_request ON funding_schedule_item (funding_request_id);
CREATE INDEX ix_funding_schedule_item_awaiting_payment ON funding_schedule_item (due_date) WHERE payment_id IS NULL;
--rollback DROP TABLE funding_schedule_item;
