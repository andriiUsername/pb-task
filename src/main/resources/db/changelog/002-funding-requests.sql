--changeset privatbank-task:create-funding-request-table
CREATE TABLE funding_request
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_wallet_id BIGINT      NOT NULL REFERENCES wallet (id),
    target_wallet_id BIGINT      NOT NULL REFERENCES wallet (id),
    currency         VARCHAR(3)  NOT NULL,
    status           VARCHAR(16) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_funding_request_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_funding_request_status CHECK (status IN ('APPROVED', 'SUSPENDED', 'PARTIALLY_PAID', 'FULLY_PAID')),
    CONSTRAINT ck_funding_request_wallets CHECK (source_wallet_id <> target_wallet_id)
);
--rollback DROP TABLE funding_request;

